import { abrir } from "../integracao-g2/harness.mjs";
const cat = (n, v) => ({ id: "rec_cat" + n, rec: true, tipoFonte: "catalogo", origemId: "aptidao:aura_do_bastiao", origemNome: "Aura do Bastião", aplicadoPor: "Aliado " + n, beneficios: [{ canal: "defesa", valor: v }], rodadas: null });
const sessao = { combate: { ativo: true }, rodada: 2, buffs: [cat(1, 2), cat(2, 3)], condicoes: [] };
const { browser, page } = await abrir({ amostraId: "minamoto", viewport: { width: 1440, height: 900 }, sessao, query: "?ficha-g2=1" });
const cdp = await page.context().newCDPSession(page);
await page.waitForTimeout(1500);
await page.locator('[data-afty-aba="buffs"]').click();
await page.getByRole("button", { name: /Adicionar/ }).first().click();
await page.getByRole("button", { name: /^Habilidades de Classe/ }).first().click();
await page.locator(".e-g2 .e-area").getByText("Ataque Concentrado", { exact: true }).first().click();
await page.locator(".e-g2 .e-area").getByRole("button", { name: "Ativar", exact: true }).last().click();
await page.waitForTimeout(800);
await cdp.send("Profiler.enable"); await cdp.send("Profiler.setSamplingInterval", { interval: 100 }); await cdp.send("Profiler.start");
await page.getByRole("button", { name: /Confirmar Ativação/ }).click();
await page.waitForTimeout(1500);
const { profile } = await cdp.send("Profiler.stop");
const { nodes, samples, timeDeltas } = profile;
const porId = new Map(nodes.map((n) => [n.id, n])); const pai = new Map(); nodes.forEach((n) => (n.children ?? []).forEach((c) => pai.set(c, n.id)));
const quem = new Map(); let total = 0, derives = 0;
samples.forEach((s, i) => {
  const t = timeDeltas[i] ?? 0; total += t;
  const cadeia = []; for (let x = s; x != null; x = pai.get(x)) cadeia.push(porId.get(x));
  const k = cadeia.findIndex((n) => n.callFrame.functionName === "deriveAfty");
  if (k < 0) return; derives += t;
  const ch = cadeia.slice(k + 1).filter((n) => n.callFrame.url.includes("/ficha/")).map((n) => n.callFrame.functionName || "(anon)").filter((x) => !/^(\(anon\)|comAddons|derivar)$/.test(x)).slice(0, 5).join(" < ");
  quem.set(ch, (quem.get(ch) ?? 0) + t);
});
console.log("total amostrado", (total / 1000).toFixed(0), "ms; dentro do derive", (derives / 1000).toFixed(0), "ms");
[...quem.entries()].sort((a, b) => b[1] - a[1]).slice(0, 12).forEach(([k, v]) => console.log((v / 1000).toFixed(0).padStart(5), "ms", k));
await browser.close();
