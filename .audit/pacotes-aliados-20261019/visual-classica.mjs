/* A ficha clássica com instâncias recebidas: a linha da aba Buffs diz o nome, de quem veio e os benefícios. Uso: BASE=... node <este arquivo> */
import fs from "node:fs";
import { chromium } from "playwright";
import { register } from "node:module";
register("data:text/javascript,export async function resolve(s,c,n){try{return await n(s,c)}catch(e){if(s.startsWith(\".\")&&!s.endsWith(\".js\"))return n(s+\".js\",c);throw e}}", import.meta.url);
const PA = await import(new URL("../../src/systems/afty/ficha/pacotes-aliados.js", import.meta.url).href);
const DIR = `${process.cwd()}/.audit/pacotes-aliados-20261019`;
const BASE = process.env.BASE ?? "http://127.0.0.1:5320";
const { fichas } = JSON.parse(fs.readFileSync(`${DIR}/fichas.json`, "utf8"));
const lido = PA.lerArquivoDePacote(fs.readFileSync(`${DIR}/pacote-yuki-rev1.json`, "utf8"));
const bib = PA.gravarNaBiblioteca([], lido.pacote, lido.recusadas, "2026-10-19T22:00:00Z").biblioteca;
const insts = ["Aura do Bastião", "Escudo Dourado", "Nue · Clareza"].map((n, i) => PA.instanciaDaOpcao(bib[0], bib[0].opcoes.find((o) => o.nome === n), { id: `vc${i}` }));
const ficha = { ...fichas.receptor, pacotesRecebidos: bib };
const browser = await chromium.launch({ channel: "chrome" });
const p = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const erros = []; p.on("pageerror", (e) => erros.push(e.message));
await p.goto(`${BASE}/Player`, { waitUntil: "domcontentloaded" });
await p.evaluate(([f, s]) => { localStorage.setItem("fm_creatures_player_v1", JSON.stringify([f])); localStorage.setItem(`fm_ficha_sessao_afty_v1:${f.id}`, JSON.stringify(s)); }, [ficha, { combate: { ativo: true }, rodada: 1, buffs: insts, condicoes: [] }]);
await p.goto(`${BASE}/Player`, { waitUntil: "domcontentloaded" });
await p.getByText(ficha.name, { exact: true }).first().click();
await p.locator("#afty-ficha").waitFor();
await p.locator('[data-afty-aba="buffs"]').click();
await p.waitForTimeout(1200);
const secao = p.getByText("Buffs de Mesa").first();
await secao.scrollIntoViewIfNeeded();
await p.screenshot({ path: `${DIR}/visual-classica-buffs.png` });
const linhas = await p.locator(".afty-linha").filter({ hasText: "De Yuki" }).allTextContents();
console.log(JSON.stringify({ linhas, defesa: await p.locator('[data-afty-stat="defesa"]').first().textContent(), erros }, null, 1));
await browser.close();
