import fs from "node:fs";
import { chromium } from "playwright";
const DIR = `${process.cwd()}/.audit/pacotes-aliados-20261019`;
const BASE = "http://127.0.0.1:5320";
const { fichas } = JSON.parse(fs.readFileSync(`${DIR}/fichas.json`, "utf8"));
const A = fichas.suporteA;
const browser = await chromium.launch({ channel: "chrome" });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const p = await ctx.newPage();
p.setDefaultTimeout(8000);
p.on("pageerror", (e) => console.log("ERRO", e.message));
p.on("console", (m) => { const t = m.text(); if (/goToDashboard|warn|error/i.test(m.type())) console.log("console", m.type(), t.slice(0, 200)); });
await p.goto(`${BASE}/Player`, { waitUntil: "domcontentloaded" });
await p.evaluate((f) => localStorage.setItem("fm_creatures_player_v1", JSON.stringify([f])), A);
const onde = async (rot) => console.log(rot, "ficha?", await p.locator("#afty-ficha").count(), "aliados?", await p.locator("[data-para-aliados]").count(), "export?", await p.locator("[data-exportar-pacote]").count());
const abre = async () => { await p.goto(`${BASE}/Player?ficha-g2=1`, { waitUntil: "domcontentloaded" }); await p.getByText(A.name, { exact: true }).first().click(); await p.locator("#afty-ficha").waitFor(); await p.waitForTimeout(700); };
await abre();
await p.locator('[data-afty-aba="buffs"]').click(); await p.waitForTimeout(300);
await p.locator("[data-adicionar]").first().click(); await p.waitForTimeout(300);
await p.locator("[data-aba-aliados]").click();
await p.locator("[data-novo-pacote]").click();
for (const chave of ["aptidao|aura_do_bastiao", "aptidao|aura_do_comandante", "habilidade|sup_inimigo_comum"]) await p.locator(`[data-fonte="${chave}"] button.k-acao`).click();
await p.locator("[data-voltar-pacote]").click();
await p.locator('[data-campo="nome-pacote"]').fill("Apoio do Grupo");
await p.locator(".k-fila[data-item]").filter({ hasText: "Aura do Comandante" }).first().locator(".k-item").click();
await p.locator('[data-campo="escolha-versao"]').selectOption("evoluida");
await p.locator("[data-salvar-pacote]").click();
await p.waitForTimeout(700);
await onde("depois de salvar");
const [d1] = await Promise.all([p.waitForEvent("download"), p.locator("[data-exportar-pacote]").click()]);
await d1.saveAs(`${DIR}/_d1.json`);
await p.waitForTimeout(400);
await onde("depois do export 1");
const [d2] = await Promise.all([p.waitForEvent("download"), p.locator("[data-exportar-pacote]").click()]);
await d2.saveAs(`${DIR}/_d2.json`);
await p.waitForTimeout(400);
await onde("depois do export 2");
await p.waitForTimeout(1500);
await onde("1,5 s depois");
await browser.close();
