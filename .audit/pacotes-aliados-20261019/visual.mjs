/* Conferência visual dos Recebidos (2026-10-19): detalhe da opção com a prévia, cartão ativo com prazo e condições, e o painel compacto.
   Contexto isolado; a biblioteca é a do arquivo exportado pelo e2e (pacote-yuki-rev1.json). Uso: BASE=... node <este arquivo> */
import fs from "node:fs";
import { chromium } from "playwright";
const DIR = `${process.cwd()}/.audit/pacotes-aliados-20261019`;
const BASE = process.env.BASE ?? "http://127.0.0.1:5320";
const TAG = new URL(BASE).port;
const LARG = Number(process.env.LARGURA ?? 1440);
const { fichas } = JSON.parse(fs.readFileSync(`${DIR}/fichas.json`, "utf8"));
const arq = JSON.parse(fs.readFileSync(`${DIR}/pacote-yuki-rev1.json`, "utf8"));
const browser = await chromium.launch({ channel: "chrome" });
const ctx = await browser.newContext({ viewport: { width: LARG, height: 900 } });
const p = await ctx.newPage();
const erros = [];
p.on("pageerror", (e) => erros.push(e.message));
await p.goto(`${BASE}/Player`, { waitUntil: "domcontentloaded" });
await p.evaluate((f) => localStorage.setItem("fm_creatures_player_v1", JSON.stringify([f])), fichas.receptor);
await p.goto(`${BASE}/Player?ficha-g2=1`, { waitUntil: "domcontentloaded" });
await p.getByText(fichas.receptor.name, { exact: true }).first().click();
await p.locator("#afty-ficha").waitFor();
await p.waitForTimeout(700);
await p.locator('[data-afty-aba="buffs"]').click();
await p.locator("[data-adicionar]").first().click();
await p.locator("[data-aba-externa]").click();
await p.locator("[data-abrir-importar]").click();
await p.locator("[data-colar-pacote]").fill(JSON.stringify(arq));
await p.locator("[data-conferir-pacote]").click();
await p.locator("[data-salvar-importacao]").click();
await p.waitForTimeout(600);
const chave = (nome) => `recebido:${arq.emissor.id}:${arq.pacote.id}:${arq.opcoes.find((o) => o.nome === nome).id}`;
await p.locator(`[data-chave-opcao="${chave("Aura do Comandante Evoluída")}"] button.k-item`).click();
await p.waitForTimeout(700);
await p.screenshot({ path: `${DIR}/visual-${TAG}-${LARG}-detalhe-recebido.png` });
await p.locator(`[data-ativar-recebido="${chave("Aura do Comandante Evoluída")}"]`).click();
await p.waitForTimeout(300);
await p.locator(`[data-chave-opcao="${chave("Escudo Dourado")}"] button.k-item`).click();
await p.locator(`[data-ativar-recebido="${chave("Escudo Dourado")}"]`).click();
await p.waitForTimeout(300);
/* A busca do catálogo (Da Ficha) acha o recebido pelo nome. */
await p.locator("[data-voltar-ativos]").click();
await p.locator("[data-adicionar]").first().click();
await p.locator("[data-busca-catalogo]").fill("Bastião");
await p.waitForTimeout(300);
const achou = await p.locator(`[data-chave-opcao="${chave("Aura do Bastião")}"]`).count();
await p.screenshot({ path: `${DIR}/visual-${TAG}-${LARG}-busca-catalogo.png` });
await p.locator("[data-voltar-ativos]").click();
await p.waitForTimeout(300);
const sess = await p.evaluate(() => Object.keys(localStorage).filter((k) => k.startsWith("fm_ficha_sessao")));
const cartao = p.locator('[data-chave-ativo^="rec:"]').filter({ hasText: "Aura do Comandante Evoluída" }).first();
await cartao.click();
await p.waitForTimeout(500);
await p.screenshot({ path: `${DIR}/visual-${TAG}-${LARG}-cartao-detalhe.png` });
const termina = await p.locator(".d-exp [data-termina]").allTextContents();
const rodape = await p.locator(".d-exp .x-rodape").textContent();
/* O painel compacto: o botão Efeitos do cabeçalho. */
await p.getByRole("button", { name: /^Efeitos/ }).first().click().catch(() => {});
await p.waitForTimeout(500);
await p.locator('[data-afty-aba="acoes"]').click().catch(() => {});
await p.waitForTimeout(500);
await p.screenshot({ path: `${DIR}/visual-${TAG}-${LARG}-compacta.png` });
const compactas = await p.locator(".e-lado").getByText(/Aura do Comandante Evoluída|Escudo Dourado/).count();
console.log(JSON.stringify({ achouNaBusca: achou, termina, rodape, compactas, sess: sess.length, erros }, null, 1));
await browser.close();
