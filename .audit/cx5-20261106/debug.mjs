import { chromium } from "playwright";
const caminho = ".audit/cx5-20261106/ficha-teste.json";
const browser = await chromium.launch({ channel: "chrome", ignoreDefaultArgs: ["--hide-scrollbars"] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await ctx.newPage();
page.setDefaultTimeout(15000);
await page.goto("http://localhost:5173/Player", { waitUntil: "networkidle" });
await page.getByRole("button", { name: "Importar", exact: true }).click();
await page.locator("input[type=file]").setInputFiles(caminho);
await page.getByText("Teste CX5 Pulseiras", { exact: true }).first().waitFor();
await page.getByRole("dialog").getByRole("button", { name: "Fechar", exact: true }).last().click();
await page.getByText("Teste CX5 Pulseiras", { exact: true }).first().click();
await page.waitForTimeout(800);
console.log("TABS:", await page.getByRole("tab").allInnerTexts());
const aba = page.getByRole("tab", { name: /Equipamentos/ }).first();
console.log("tem aba:", await aba.count());
await aba.click();
await page.waitForTimeout(500);
await page.locator("button, [role=tab]").filter({ hasText: /^Itens/ }).first().click();
await page.waitForTimeout(600);
const t = await page.innerText("body");
console.log(t.slice(t.indexOf("INVENT"), t.indexOf("INVENT") + 900));
await page.screenshot({ path: ".audit/cx5-20261106/shots/debug.png" });
await browser.close();
