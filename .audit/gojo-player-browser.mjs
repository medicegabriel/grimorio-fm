import { chromium } from "playwright";
import { mkdir, writeFile } from "node:fs/promises";
import assert from "node:assert/strict";
await mkdir(".audit/gojo-player-shots",{recursive:true});
const browser = await chromium.launch({channel:"chrome",ignoreDefaultArgs:["--hide-scrollbars"]});
const report = [];
try {
 for (const largura of [1440,390]) {
  const ctx=await browser.newContext({viewport:{width:largura,height:1000},isMobile:largura===390,hasTouch:largura===390});
  const page=await ctx.newPage();page.setDefaultTimeout(15000);
  const erros=[];page.on("pageerror",e=>erros.push(e.message));
  await page.goto("http://localhost:5173/Player",{waitUntil:"networkidle"});
  await page.getByRole("button",{name:"Importar",exact:true}).click();
  await page.locator("input[type=file]").setInputFiles("previas/satoru-gojo-player.json");
  await page.getByText("Satoru Gojo (Prévia Player)",{exact:true}).first().waitFor();
  await page.getByRole("dialog").getByRole("button",{name:"Fechar",exact:true}).last().click();
  const imported=await page.evaluate(()=>JSON.parse(localStorage.getItem("fm_creatures_player_v1")));
  assert.equal(imported.length,1);assert.equal(imported[0].rulesVersion,"player");assert.equal(imported[0].addons.length,4);
  await page.getByText("Satoru Gojo (Prévia Player)",{exact:true}).first().click();
  await page.screenshot({path:".audit/gojo-player-shots/ficha-"+largura+".png"});
  await page.locator('button[title="Editar no criador"]').click();
  const nd=()=>page.locator('input[type="number"]').first();
  assert.equal(await nd().inputValue(),"35");assert.equal(await nd().getAttribute("max"),null);
  await nd().fill("36");await nd().press("Tab");
  await page.getByRole("tab",{name:"Interlúdios",exact:true}).click();
  const focos=page.locator('[title^="Focos totais: Nível"]').first();
  assert.match(await focos.innerText(),/82\s*\/\s*54/);
  assert.equal(await page.getByRole("spinbutton",{name:"Total de Focos de Interlúdio"}).count(),0);
  await page.getByRole("tab",{name:"Identidade",exact:true}).click();
  await nd().fill("35");await nd().press("Tab");
  await page.getByRole("tab",{name:"Interlúdios",exact:true}).click();
  assert.match(await focos.innerText(),/82\s*\/\s*52/);
  await focos.scrollIntoViewIfNeeded();
  await page.screenshot({path:".audit/gojo-player-shots/interludios-"+largura+".png"});
  await page.getByRole("tab",{name:"Especializações",exact:true}).click();
  const grupo=page.getByRole("group",{name:"Especializações",exact:true});
  assert.equal(await grupo.locator('button[aria-pressed="true"]').count(),3);
  await page.getByRole("tab",{name:/Habilidades Lendárias/}).click();
  assert.equal(await page.getByRole("button",{name:"Escolher Invencível",exact:true}).isDisabled(),true);
  assert.equal(await page.getByRole("button",{name:"Escolher Manipulação Avançada de Energia",exact:true}).isDisabled(),true);
  assert.equal(await page.getByRole("button",{name:"Escolher Atingir Ápice",exact:true}).isEnabled(),true);
  await page.getByRole("button",{name:"Escolher Invencível",exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:".audit/gojo-player-shots/lendarias-"+largura+".png"});
  await page.getByRole("button",{name:"Escolher Dominância em Técnica",exact:true}).click();
  await page.getByRole("button",{name:"Dominância em Técnica",exact:true}).click();
  await page.getByRole("button",{name:"5 variações de Feitiço",exact:true}).click();
  await page.getByRole("tab",{name:"Habilidades",exact:true}).click();
  const variacao=page.getByRole("checkbox",{name:"Variação de Feitiço (Dominância em Técnica)",exact:true});
  assert.equal(await variacao.count(),1);
  await variacao.check();await variacao.scrollIntoViewIfNeeded();
  assert.equal(await variacao.isChecked(),true);
  assert.equal(await page.locator('[title="Vagas exclusivas de Variação de Feitiço"]').innerText(),"+1 / 5");
  await page.screenshot({path:".audit/gojo-player-shots/variacoes-"+largura+".png"});
  await page.getByRole("button",{name:"Salvar Alterações",exact:true}).click();
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem("fm_creatures_player_v1"))[0]);
  assert.equal(saved.core.nd,35);assert.equal(saved.feiticos[0].variacaoDeTecnica,true);
  assert.deepEqual(saved.escolhasAltoNivel.len_dominancia_em_tecnica,["variacoes"]);
  assert.deepEqual(erros,[]);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  report.push({largura,importacao:true,nivel35:true,nivel36:true,interludios52:true,classes3:true,preRequisitos:true,variacoes:true,persistencia:true,erros});
  await ctx.close();
 }
 await writeFile(".audit/gojo-player-report.json",JSON.stringify(report,null,2));
 console.log(JSON.stringify(report));
} finally { await browser.close(); }
