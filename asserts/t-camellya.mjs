import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { register } from 'node:module';
register('data:text/javascript,export async function resolve(s,c,n){try{return await n(s,c)}catch(e){if(s.startsWith(".")&&!s.endsWith(".js"))return n(s+".js",c);throw e}}', import.meta.url);
const { deriveAfty } = await import('../src/systems/afty/afty-derive.js');
const AD = await import('../src/systems/afty/afty-addons.js');
const { createBlankAfty, funcionamentosDaFicha } = await import('../src/systems/afty/afty-schema.js');
const F = await import('../src/systems/afty/afty-feiticos.js');
const AC = await import('../src/systems/afty/afty-acoes-addon.js');
const pacote = JSON.parse(readFileSync(new URL('../addons/camellya.json', import.meta.url), 'utf8'));
let n = 0;
const eq = (real, esperado, msg) => { assert.deepEqual(real, esperado, msg); n++; };
eq(AD.validarPacote(pacote), [], 'pacote importável');
eq(pacote.feiticos.map((f) => f.tipo), ['passivo', 'dano', 'dano', 'dano', 'dano', 'auxiliar', 'auxiliar', 'especial'], 'categorias nativas, sem atalho Personalizado');
eq(pacote.feiticos.some((f) => f.categoriaPassivo === 'personalizado'), false, 'passiva sem categoria personalizada');
eq(pacote.feiticos.some((f) => ['rolagens', 'custoPETexto', 'acaoPersonalizada', 'alcanceTexto'].some((k) => k in f)), false, 'nenhum campo do formulário personalizado');
eq(pacote.acoesMotor.map((a) => a.id), ['sementes'], 'sem controles duplicados de Jardim e Transformação');
eq(pacote.estadosCombate, undefined, 'sem contexto antigo independente da sustentação');
eq(JSON.stringify(pacote).includes(String.fromCharCode(0x2014)), false);
eq(JSON.stringify(pacote).includes(';'), false);
const ctx = { nd: 26, modTecnica: 0, cdBase: 61, maestria: 8, sistema: 'afty' };
const calc = (id) => F.calcularFeitico(pacote.feiticos.find((f) => f.id === id), ctx);
const vinha = calc('vinha'), chicote = calc('chicote'), germ = calc('germinacao'), flor = calc('floracao');
eq([vinha.dano, vinha.alcance, vinha.custoPE], ['2d10', 3, 0], 'ataque básico pelas trocas nativas');
eq([chicote.dano, chicote.alcance, chicote.custoPE], ['25d12+52', 18, 20], 'ataque nível 5 com Conjuração Aprimorada');
eq([germ.dano, germ.alcance, germ.custoPE, germ.reducaoCondicoes], ['8d8', 18, 8, 5], 'Imóvel paga o custo em dados no nível nativo legal');
eq([flor.dano, flor.alcance, flor.area, flor.custoPE], ['12d10+26', 24, 6, 12], 'esfera com trocas reais de área e alcance');
eq([calc('jardim').valor, calc('jardim').upkeepPE], [1, 1], 'Percepção sustentada pela tabela');
eq([calc('calice').valor, calc('calice').umGolpe], [28, true], 'RD dobra somente no evento único');
eq(calc('transformacao').efeitos.map((e) => [e.efeito, e.valor]), [['defesa', 4], ['movimento', 13.5], ['danoDurante', [3, 8]]], 'três efeitos reais de transformação');
eq(calc('transformacao').sustentacaoPE, 5);
for (const f of pacote.feiticos) eq(F.calcularFeitico(f, ctx).avisos, [], `${f.nome} válido no criador nativo`);
for (const sistema of ['afty', 'player']) {
  const c = createBlankAfty();
  c.rulesVersion = sistema; c.core.nd = 26; c.core.tipo = 'conjurador';
  c.core.tecnicaAttr = 'sabedoria'; c.core.patamar = 'calamidade';
  c.especializacoes = [{ id: 'conjurador', nivel: 26 }];
  c.addons = [pacote]; AD.aplicarAddons(c.addons);
  const modelos = AD.feiticosDeAddon(c, 5);
  c.feiticos = modelos;
  const derive = (combate = {}, addons = c.addons, feiticos = c.feiticos) => {
    AD.aplicarAddons(addons);
    return deriveAfty({ ...c, addons, feiticos, combate: { ativo: true, ...combate } });
  };
  const antes = JSON.stringify(c), base = derive();
  eq(JSON.stringify(c), antes, 'derive não escreve na ficha');
  eq(funcionamentosDaFicha(c).filter((f) => f.id.startsWith('camellya:')).map((f) => f.id), ['camellya:tecnica'], 'só Funcionamento Básico no perfil');
  eq(modelos.length, 8);
  eq(AD.feiticosDeAddon(c, 2).map((f) => f.addonModeloId), ['marca', 'vinha', 'jardim'], 'Germinação não aparece antes de poder aplicar Imóvel');
  eq(base.feiticos.lista.flatMap((f) => f.avisos), [], 'nenhum aviso nativo na ficha');
  const transformada = derive({ sustentacaoFeitico1: 'camellya:transformacao' });
  eq(transformada.defesa - base.defesa, 4, 'Defesa vem da transformação nativa');
  eq(transformada.movimento - base.movimento, 13.5, 'movimento vem da transformação nativa');
  eq(transformada.auxiliaresAtivos.dados.map((d) => [d.dados, d.faces]), [[3, 8]], 'dano Durante Ataque integrado');
  eq(transformada.auxiliaresAtivos.ativos.map((a) => a.sustentacaoPE), [5], 'manutenção nativa de 5 PE');
  const jardim = derive({ sustentacaoFeitico1: 'camellya:jardim' });
  eq(jardim.atencao - base.atencao, 1, 'Percepção sustentada realmente altera o cálculo');
  eq(jardim.auxiliaresAtivos.ativos.map((a) => a.sustentacaoPE), [1]);
  const calice = derive({ 'feiticoLigado_camellya:calice': true });
  eq(calice.rdGeral - base.rdGeral, 28, 'RD do evento pela ativação nativa');
  const antiga = derive({ 'acaoAddon:camellya:transformacao': 1, 'acaoAddon:camellya:jardim': 1 });
  eq([antiga.defesa, antiga.atencao], [base.defesa, base.atencao], 'estados da versão anterior não duplicam efeitos');
  const desligada = derive({ ativo: false, sustentacaoFeitico1: 'camellya:transformacao' });
  eq([desligada.defesa, desligada.movimento], [base.defesa, base.movimento], 'fora de combate encerra efeitos');
  const semFeitico = derive({ sustentacaoFeitico1: 'camellya:transformacao' }, c.addons, []);
  eq(semFeitico.auxiliaresAtivos.ativos, [], 'sem adquirir o modelo não há bônus de transformação');
  eq(AD.modelosPendentesDeAddon(c, 5, modelos), [], 'sem duplicar modelos já atualizados');
  eq(AD.modelosPendentesDeAddon(c, 5, modelos.map((f) => ({ ...f, addonVersao: '1.1.0' }))).every((f) => f.situacaoModelo === 'desatualizado'), true, 'atualização das cópias antigas oferecida');
  const sementes = base.acoesAddon.find((a) => a.id === 'sementes');
  eq(AC.definirAcaoAddon({ combate: { ativo: true } }, sementes, 99).combate[sementes.estado], 2, 'contador continua limitado a duas sementes');
  eq(derive({}, [], []).acoesAddon, [], 'desativação retira o contador');
}
AD.limparAddons();
console.log(`TODOS OS ${n} ASSERTS PASSARAM`);
