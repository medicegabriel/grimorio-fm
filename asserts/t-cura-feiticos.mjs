import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { register } from "node:module";
register('data:text/javascript,export async function resolve(s,c,n){try{return await n(s,c)}catch(e){if(s.startsWith(".")&&!s.endsWith(".js"))return n(s+".js",c);throw e}}', import.meta.url);
const R = new URL("../src/systems/afty/", import.meta.url).href;
const { deriveAfty } = await import(R + "afty-derive.js");
const { createBlankAfty } = await import(R + "afty-schema.js");
const { normalizarPacote, validarPacote, aplicarAddons, feiticosDeAddon } = await import(R + "afty-addons.js");
const { getCanal, canaisSemGrupo } = await import(R + "afty-efeitos.js");
const { curaNoGasto, preparaRolagemCura, rerrolagemDeCura } = await import(R + "afty-cura.js");
const { rolarDano } = await import(R + "ficha/ficha-rolagem.js");
const pacote = normalizarPacote(JSON.parse(readFileSync(new URL("../addons/cura-aperfeicoada-feiticos.json", import.meta.url), "utf8")));
let ok = 0;
const t = (nome, real, esperado) => { assert.deepEqual(real, esperado, nome); ok++; };
const rngDe = (...valores) => {
  let i = 0;
  const rng = () => { assert.ok(i < valores.length, "não deve sortear além das tentativas fornecidas"); return (valores[i++] - 0.5) / 8; };
  rng.usados = () => i;
  return rng;
};
t("addon válido", validarPacote(pacote), []);
t("novo canal tem alvo de cura", getCanal("rerrolaCuraContinua")?.alvo, "fonteCura");
t("novo canal tem grupo", canaisSemGrupo().includes("rerrolaCuraContinua"), false);
for (const sistema of ["afty", "player"]) {
  aplicarAddons([pacote]);
  const c = createBlankAfty();
  c.rulesVersion = sistema;
  c.core.nd = 20;
  c.especializacoes = [{ id: "suporte", nivel: 20 }];
  c.habilidades = ["sup_cura_aperfeicoada"];
  c.aptidoesAmaldicoadas = ["energia_reversa", "cura_amplificada"];
  c.aptidoes.er = 3;
  c.addons = [pacote];
  const modelos = feiticosDeAddon(c, 5);
  t(sistema + ": modelos de nível 5", modelos.map((f) => [f.tipo, f.nivel]), [["passivo", 5], ["passivo", 5]]);
  t(sistema + ": modelos indisponíveis abaixo do nível 5", feiticosDeAddon(c, 4).length, 0);
  t(sistema + ": ativar pacote não aplica modelos sozinho", rerrolagemDeCura(deriveAfty(c).efeitos)?.ate, 2);
  const antes = JSON.stringify(c);
  for (const indices of [[], [0], [1], [0, 1]]) {
    const ficha = structuredClone(c);
    ficha.feiticos = indices.map((i) => modelos[i]);
    const d = deriveAfty(ficha);
    const regra = rerrolagemDeCura(d.efeitos);
    const limite = indices.includes(0) ? 4 : 2;
    const continua = indices.includes(1);
    t(sistema + ": limite " + indices, regra.ate, limite);
    t(sistema + ": repetição " + indices, !!regra.continua, continua);
    const rng = continua ? rngDe(2, 2, 1, limite + 1) : rngDe(2, 1);
    const desc = preparaRolagemCura({ tipo: "dano", tom: "cura", dados: 1, faces: 8, fixo: 7 }, d.efeitos);
    const r = rolarDano(desc, rng);
    t(sistema + ": resultado " + indices, r.total, (continua ? limite + 1 : 2) + 7);
    t(sistema + ": tentativas " + indices, rng.usados(), continua ? 4 : 2);
    t(sistema + ": histórico conserva cada descarte " + indices, r.rerrolados.map((x) => x.descartado), continua ? [2, 1, 2] : [1]);
    const alto = rolarDano(desc, rngDe(8));
    t(sistema + ": resultado alto não rerrola " + indices, alto.rerrolados, []);
    const semHabilidade = structuredClone(ficha);
    semHabilidade.habilidades = [];
    t(sistema + ": exige Cura Aperfeiçoada " + indices, rerrolagemDeCura(deriveAfty(semHabilidade).efeitos), null);
    const pvTemporario = { tipo: "dano", tom: "temporario", dados: 1, faces: 8 };
    t(sistema + ": PV temporário sem regra " + indices, preparaRolagemCura(pvTemporario, d.efeitos), pvTemporario);
    const invocacao = { ...desc, rerrola: undefined, curaDoUsuario: false };
    t(sistema + ": cura de invocação não recebe regra " + indices, preparaRolagemCura(invocacao, d.efeitos), invocacao);
  }
  c.feiticos = modelos;
  const d = deriveAfty(c);
  const linha = d.cura.linhas.find((l) => l.id === "cura_energia_reversa");
  const gasto = curaNoGasto(linha, 2);
  const desc = preparaRolagemCura({ tipo: "dano", tom: "cura", fonteCuraId: linha.id, dados: linha.dados, faces: 8, blocos: gasto.blocos, fixo: gasto.fixo }, d.efeitos);
  const r = rolarDano(desc, () => 0.9);
  t(sistema + ": dados por PER não mudam", r.dados.length, gasto.dados);
  t(sistema + ": fixo entra uma vez", r.total, 8 * gasto.dados + gasto.fixo);
  const especifica = structuredClone(c);
  especifica.feiticos = [];
  especifica.core.tecnicaEfeitos = [{ canal: "rerrolaCuraContinua", alvo: "cura_energia_reversa", expr: "1" }];
  const de = deriveAfty(especifica);
  t(sistema + ": repetição com alvo", !!rerrolagemDeCura(de.efeitos, "cura_energia_reversa").continua, true);
  t(sistema + ": não vaza para outra fonte", !!rerrolagemDeCura(de.efeitos, "cura_suporte_em_combate").continua, false);
  especifica.habilidades = [];
  t(sistema + ": repetição sozinha não concede limite", rerrolagemDeCura(deriveAfty(especifica).efeitos), null);
  c.feiticos = [];
  t(sistema + ": cópias não alteraram a ficha base", JSON.stringify(c), antes);
}
const continua = { dados: 1, faces: 8, tom: "cura", rerrola: { ate: 4, melhor: true, continua: true } };
for (let inicial = 1; inicial <= 8; inicial++) {
  const r = rolarDano({ ...continua, rerrola: { ...continua.rerrola, continua: false } }, rngDe(inicial, 8));
  t("limite 4 inclui exatamente 1 a 4: " + inicial, r.rerrolados.length, inicial <= 4 ? 1 : 0);
  t("resultado no limite 4: " + inicial, r.dados, [inicial <= 4 ? 8 : inicial]);
}
const descida = rolarDano(continua, rngDe(4, 1, 3, 8));
t("repetição mantém o melhor durante resultados menores", descida.rerrolados.map((x) => x.de), [4, 4, 4]);
t("repetição aceita o resultado acima do limite", descida.dados, [8]);
const longa = rolarDano(continua, rngDe(...Array(100).fill(2), 5));
t("cadeia não tem teto de tentativas", longa.rerrolados.length, 100);
t("cadeia termina acima do limite", longa.dados, [5]);
assert.throws(() => rolarDano({ ...continua, faces: 4 }, () => { throw Error("não deveria sortear"); }), /limite.*menor/); ok++;
t("dano conserva somente uma rerrolagem", rolarDano({ ...continua, tom: "dano" }, rngDe(2, 1)).dados, [2]);
aplicarAddons([]);
console.log(`TODOS OS ${ok} ASSERTS PASSARAM`);
